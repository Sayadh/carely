#!/usr/bin/env node
/**
 * Builds Carely and assembles two self-contained folders for cPanel "Setup Node.js App" (Passenger):
 *
 *   release/carely_api/  → upload to /home/<user>/carely_api   (startup file: app.js, then "Run NPM Install")
 *   release/carely_web/  → upload to /home/<user>/carely_web   (startup file: app.js, no npm install needed)
 *
 * Plus a .zip of each. Neither folder depends on the monorepo, on another site's node_modules or on secrets:
 * the shared package is vendored as a tarball and every setting comes from the server-side .env.
 *
 * Usage (on your computer, from the repo root):  node scripts/release-cpanel.mjs [--skip-build]
 */
import { execSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'release');
const apiOut = join(out, 'carely_api');
const webOut = join(out, 'carely_web');
const run = (cmd, cwd = root) => {
  console.log(`$ ${cmd}`);
  execSync(cmd, { cwd, stdio: 'inherit' });
};
const readJson = (p) => JSON.parse(readFileSync(p, 'utf8'));

// ── 1. Build (shared → api → web) and the production seed ──
if (!process.argv.includes('--skip-build')) {
  run('npm run build');
  run('npm run build:seed -w @carely/api');
}
for (const p of ['packages/shared/dist/cjs/index.js', 'apps/api/dist/main.js', 'apps/api/dist/jobs-cli.js', 'apps/api/dist-seed/prisma/seed.js', 'apps/web/.output/server/index.mjs']) {
  if (!existsSync(join(root, p))) throw new Error(`Missing build output: ${p} — run without --skip-build`);
}

rmSync(out, { recursive: true, force: true });
mkdirSync(join(apiOut, 'vendor'), { recursive: true });
mkdirSync(webOut, { recursive: true });

// ── 2. API ──
// The shared package is vendored as a tarball: npm installs a real copy (a `file:` folder would become a symlink
// into cPanel's nodevenv and break).
const shared = readJson(join(root, 'packages/shared/package.json'));
run(`npm pack --pack-destination "${join(apiOut, 'vendor')}"`, join(root, 'packages/shared'));
const sharedTgz = readdirSync(join(apiOut, 'vendor')).find((f) => f.endsWith('.tgz'));

const api = readJson(join(root, 'apps/api/package.json'));
const apiDeps = { ...api.dependencies, '@carely/shared': `file:vendor/${sharedTgz}` };
// Prisma CLI is needed on the server for `prisma generate` (engine for the server's OS) and `migrate deploy`.
apiDeps.prisma = api.devDependencies.prisma;
// S3 storage is not used on this hosting (STORAGE_DRIVER=local) and is imported lazily only when enabled.
writeFileSync(
  join(apiOut, 'package.json'),
  JSON.stringify(
    {
      name: 'carely-api',
      version: api.version,
      private: true,
      description: 'Carely API — cPanel/Passenger release (generated by scripts/release-cpanel.mjs)',
      main: 'app.js',
      engines: { node: '>=22' },
      scripts: {
        start: 'node app.js',
        'prisma:generate': 'prisma generate',
        'db:status': 'prisma migrate status',
        'db:migrate': 'prisma migrate deploy',
        'db:seed': 'node dist-seed/prisma/seed.js',
        jobs: 'node dist/jobs-cli.js',
      },
      prisma: { schema: 'prisma/schema.prisma' },
      dependencies: apiDeps,
    },
    null,
    2,
  ) + '\n',
);
cpSync(join(root, 'apps/api/dist'), join(apiOut, 'dist'), { recursive: true, filter: (s) => !s.endsWith('.map') });
cpSync(join(root, 'apps/api/dist-seed'), join(apiOut, 'dist-seed'), { recursive: true });
mkdirSync(join(apiOut, 'prisma'));
cpSync(join(root, 'apps/api/prisma/schema.prisma'), join(apiOut, 'prisma/schema.prisma'));
cpSync(join(root, 'apps/api/prisma/migrations'), join(apiOut, 'prisma/migrations'), { recursive: true });
cpSync(join(root, 'deploy/cpanel/api/app.js'), join(apiOut, 'app.js'));
cpSync(join(root, 'deploy/cpanel/api/.env.example'), join(apiOut, '.env.example'));

// ── 3. Website (Nitro output is self-contained; no npm install on the server) ──
cpSync(join(root, 'apps/web/.output'), join(webOut, '.output'), { recursive: true });
cpSync(join(root, 'deploy/cpanel/web/app.js'), join(webOut, 'app.js'));
cpSync(join(root, 'deploy/cpanel/web/.env.example'), join(webOut, '.env.example'));
writeFileSync(
  join(webOut, 'package.json'),
  JSON.stringify(
    {
      name: 'carely-web',
      version: readJson(join(root, 'apps/web/package.json')).version,
      private: true,
      description: 'Carely website — cPanel/Passenger release (generated by scripts/release-cpanel.mjs)',
      main: 'app.js',
      engines: { node: '>=22' },
      scripts: { start: 'node app.js' },
    },
    null,
    2,
  ) + '\n',
);

// Real secrets must never travel with a release.
for (const dir of [apiOut, webOut]) if (existsSync(join(dir, '.env'))) throw new Error(`Refusing to package a .env in ${dir}`);

// ── 4. Zips (macOS/Linux `zip`) ──
const stamp = new Date().toISOString().slice(0, 16).replace(/[-:T]/g, '');
for (const name of ['carely_api', 'carely_web']) run(`zip -qr ../${name}-${stamp}.zip .`, join(out, name));
console.log(`\n✓ Release ready in ${out}\n  carely_api-${stamp}.zip → /home/<user>/carely_api\n  carely_web-${stamp}.zip → /home/<user>/carely_web\n  shared: ${shared.name}@${shared.version}`);
